import java.util.*;

class Solution {
    public int solution(int[] A, int[] B) {
        // [입력] A, B: 길이 같은 숫자 배열
        //   A = A팀 출전 순서대로 각 선수 숫자 (B팀이 이미 알고 있음)
        //   B = B팀 선수들 숫자 (순서는 B팀이 마음대로 정함)
        // [출력] B > A인 경기 수의 최댓값
        //
        // [문제 요약]
        //   A 순서를 다 알기 때문에 B는 A 각 선수에게 누구를 붙일지 자유롭게 고를 수 있음
        //   → 결국 "A와 B를 1:1로 짝지어서 B가 이기는 짝을 최대로" 만드는 문제
        //   → 경기 순서는 결과에 영향 없고, 누가 누구랑 붙느냐만 중요
        //
        // [접근]
        //   n 최대 10만 → 완전탐색(n!) 불가, O(n log n) 필요 → 정렬 + 그리디
        //   그리디 아이디어: B의 약한 선수로, 이길 수 있는 가장 약한 A를 잡는다
        //   (센 선수를 약한 상대에게 낭비하지 않기 위해)

        // 둘 다 오름차순 정렬 → O(n log n)
        Arrays.sort(A);
        Arrays.sort(B);

        int answer = 0; // B팀 승점
        int i = 0;      // 아직 이기지 못한 A 중 가장 약한 선수 위치

        // B를 약한 선수부터 하나씩 확인 → O(n)
        for (int j = 0; j < B.length; j++) {
            if (B[j] > A[i]) {
                // 이길 수 있으면 그 A를 잡고 다음 A로
                answer++;
                i++;
            }
            // 못 이기면: 이 B는 남은 A 누구도 못 이김 (A[i]가 남은 것 중 제일 약하니까)
            // → 그냥 버리고 다음 B로
        }

        // i는 이길 때만 증가, j는 매번 증가 → 항상 i <= j < n 이라 인덱스 초과 없음

        // [시간복잡도] 정렬 O(n log n) + 반복 O(n) = O(n log n)
        //   큰 쪽이 전체를 결정하므로 O(n log n)
        //   n = 10만이면 약 170만 번 연산 → 충분히 통과
        return answer;
    }
}